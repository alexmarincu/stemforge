#!/usr/bin/env python3
"""Generate the PyInstaller Windows version resource from ``__version__``.

``StemForge.exe`` carries real file properties, not PyInstaller's
defaults. ``packaging/windows/build.ps1`` calls this script with the value from
``stemforge.__version__`` and passes the result to the spec through
``STEMFORGE_VERSION_FILE``.

The output is the text form PyInstaller's ``versioninfo`` module deserialises; it
is deliberately generated rather than hand-maintained so a version bump cannot
leave a stale resource behind.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """Return the four-part numeric version Windows expects.

    ``1.2.3`` becomes ``(1, 2, 3, 0)``; a pre-release or local suffix is ignored
    for the binary resource while the string fields keep the exact version.
    """
    core = version.split("+", 1)[0].split("-", 1)[0]
    parts = core.split(".")
    if not 1 <= len(parts) <= 3 or any(not part.isdigit() for part in parts):
        raise ValueError(f"not a numeric semver version: {version!r}")
    numbers = [int(part) for part in parts]
    while len(numbers) < 3:
        numbers.append(0)
    return numbers[0], numbers[1], numbers[2], 0


def render(version: str, *, copyright_year: int = 2026) -> str:
    """Render the ``VSVersionInfo`` text for ``version``."""
    major, minor, patch, build = version_tuple(version)
    copyright = f"Copyright (C) {copyright_year} the StemForge contributors. GPL-3.0-only."
    return f"""# UTF-8
#
# Generated by packaging/windows/version_info.py from stemforge.__version__.
# Do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({major}, {minor}, {patch}, {build}),
    prodvers=({major}, {minor}, {patch}, {build}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904B0',
          [
            StringStruct('CompanyName', 'StemForge contributors'),
            StringStruct('FileDescription', 'StemForge'),
            StringStruct('FileVersion', '{version}'),
            StringStruct('InternalName', 'StemForge'),
            StringStruct('LegalCopyright', '{copyright}'),
            StringStruct('OriginalFilename', 'StemForge.exe'),
            StringStruct('ProductName', 'StemForge'),
            StringStruct('ProductVersion', '{version}'),
            StringStruct(
              'Comments',
              'GPL-3.0-only. See LICENSE and THIRD_PARTY_NOTICES.md.'
            )
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True, help="the stemforge.__version__ value")
    parser.add_argument("--output", required=True, type=Path, help="write the version file here")
    parser.add_argument("--copyright-year", type=int, default=2026)
    args = parser.parse_args(argv)

    try:
        text = render(args.version, copyright_year=args.copyright_year)
    except ValueError as error:
        parser.error(str(error))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
