def test_a_failed_final_rename_removes_the_partial_and_leaves_no_file(
    tmp_path: Path,
    ffmpeg_path: Path,
    media: FfmpegTool,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    store = _store(tmp_path)
    canonical = _make_tone(ffmpeg_path, tmp_path / "tone.wav")
    _commit_source(store, canonical)
    destination = tmp_path / "exports"
    destination.mkdir()

    def fail_commit(partial: Path, **kwargs: object) -> Path:
        raise OSError(errno.EIO, "injected rename failure")

    monkeypatch.setattr(export_job, "_commit_without_overwrite", fail_commit)

    with pytest.raises(StemForgeError) as raised:
        _export(store, media, "master", ExportFormat.WAV24, destination)

    assert raised.value.code == errors.EXPORT_WRITE_FAILED
    assert raised.value.detail == "other"
    assert raised.value.retryable is True
    assert list(destination.iterdir()) == []
    assert not (store.staging_dir / "job-export").exists()
    assert not list(destination.glob("*.partial"))


