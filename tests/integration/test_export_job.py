@pytest.mark.parametrize(
    ("fmt", "suffix", "codec", "bit_depth", "bit_rate", "has_cover"),
    [
        (ExportFormat.WAV24, ".wav", "pcm_s24le", 24, None, False),
        (ExportFormat.FLAC24, ".flac", "flac", 24, None, True),
        (ExportFormat.MP3_320, ".mp3", "mp3", None, 320_000, True),
    ],
)
def test_each_format_round_trips_codec_depth_rate_tags_cover_and_peak(
    tmp_path: Path,
    ffmpeg_path: Path,
    ffprobe_path: Path,
    cover_png: Path,
    media: FfmpegTool,
    fmt: ExportFormat,
    suffix: str,
    codec: str,
    bit_depth: int | None,
    bit_rate: int | None,
    has_cover: bool,
) -> None:
    store = _store(tmp_path)
    canonical = _make_tone(ffmpeg_path, tmp_path / "tone.wav")
    _commit_source(store, canonical, cover=cover_png)
    destination = tmp_path / "exports"
    destination.mkdir()
    events: list[tuple[float, str | None, str | None]] = []

    result = _export(store, media, "master", fmt, destination, events=events)

    assert result.path.parent == destination
    assert result.path.name == f"{TITLE}{suffix}"
    assert result.fmt is fmt
    assert result.gain_db == 0.0
    _assert_no_partial(destination)
    assert sorted(path.name for path in destination.iterdir()) == [result.path.name]

    info = media.probe(result.path)
    assert info.codec == codec
    assert info.format == {"wav": "wav", "flac": "flac", "mp3": "mp3"}[fmt.suffix[1:]]
    assert info.sample_rate == 44_100
    assert info.channels == 2
    _assert_duration(info.duration_s)
    if bit_depth is not None:
        assert info.bit_depth == bit_depth
    if bit_rate is not None:
        assert info.bit_rate == bit_rate

    document = _probe_json(ffprobe_path, result.path)
    assert _has_attached_picture(document) is has_cover
    expected_tags = WAV_INFO_TAGS if fmt is ExportFormat.WAV24 else TAGS.keys()
    for key in expected_tags:
        assert info.tags[key] == TAGS[key], (fmt, key, info.tags)
    if fmt is ExportFormat.WAV24:
        # No WAV comment tag, hence no ICMT INFO chunk.
        assert "comment" not in info.tags
        assert b"ICMT" not in result.path.read_bytes()

    source_peak = _peaks(media, canonical)
    output_peak = _peaks(media, result.path)
    assert abs(output_peak - source_peak) <= 0.1, (fmt, source_peak, output_peak)

    stages = [stage for _, stage, _ in events]
    assert stages[0] == STAGE_ENCODING
    assert STAGE_TAGGING in stages
    assert stages[-1] == STAGE_WRITING
    assert stages.index(STAGE_ENCODING) < stages.index(STAGE_TAGGING)
    assert stages.index(STAGE_TAGGING) < stages.index(STAGE_WRITING)


def test_the_recorded_shared_gain_is_applied_once_and_recorded(
    tmp_path: Path,
    ffmpeg_path: Path,
    media: FfmpegTool,
) -> None:
    store = _store(tmp_path)
    canonical = _make_tone(
        ffmpeg_path,
        tmp_path / "hot.wav",
        expression="2*sin(2*PI*440*t)|2*sin(2*PI*440*t)",
    )
    _commit_source(store, canonical, gain_db=-7.0)
    destination = tmp_path / "exports"
    destination.mkdir()

    result = _export(store, media, "master", ExportFormat.WAV24, destination)

    source_peak = _peaks(media, canonical)
    output_peak = _peaks(media, result.path)
    assert source_peak > 0.0
    assert output_peak <= 0.0
    assert abs(output_peak - (source_peak - 7.0)) <= 0.1
    assert result.manifest["gain_db"] == pytest.approx(-7.0)
    assert result.manifest["normalization"] == "none"
    assert result.manifest["target"] == "master"


