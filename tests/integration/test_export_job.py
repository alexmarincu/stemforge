    destination.mkdir()

    first = _export(store, media, "master", ExportFormat.WAV24, destination, job_id="job-1")
    first_hash = hashlib.sha256(first.path.read_bytes()).hexdigest()
    second = _export(store, media, "master", ExportFormat.WAV24, destination, job_id="job-2")
