def _probe_json(ffprobe_path: Path, path: Path) -> dict[str, object]:
    result = subprocess.run(
        [
            str(ffprobe_path),
            "-v",
            "error",
            "-print_format",
            "json",
            "-show_format",
            "-show_streams",
            str(path),
        ],
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
    )
    assert result.returncode == 0, result.stderr
    payload = json.loads(result.stdout)
    assert isinstance(payload, dict)
    return payload


def _has_attached_picture(payload: dict[str, object]) -> bool:
    streams = payload["streams"]
    assert isinstance(streams, list)
    return any(
        isinstance(stream, dict)
        and stream.get("codec_type") == "video"
        and isinstance(stream.get("disposition"), dict)
        and stream["disposition"].get("attached_pic") == 1
        for stream in streams
    )


def _assert_duration(actual: float, expected: float = DURATION_S) -> None:
    assert abs(actual - expected) <= 0.050, (actual, expected)


def _peaks(media: FfmpegTool, path: Path) -> float:
    return media.peak_dbfs(path, cancel=CancelToken(), log=LOG)


def _assert_no_partial(directory: Path) -> None:
    assert not list(directory.glob("*.partial")), list(directory.iterdir())


