def _run(executable: Path, *arguments: object) -> None:
    result = subprocess.run(
        [str(executable), *(str(argument) for argument in arguments)],
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
    )
    assert result.returncode == 0, result.stderr


def _entry(path: Path, role: str) -> dict[str, object]:
    data = path.read_bytes()
    return {
        "path": path.name,
        "role": role,
        "size": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
    }


def _make_tone(
    ffmpeg_path: Path,
    target: Path,
    *,
    expression: str = "0.5*sin(2*PI*440*t)|0.5*sin(2*PI*440*t)",
    duration: float = DURATION_S,
) -> Path:
    _run(
        ffmpeg_path,
        "-v",
        "error",
        "-y",
        "-f",
        "lavfi",
        "-i",
        f"aevalsrc={expression}:s=44100:d={duration}:c=stereo",
        "-c:a",
        "pcm_f32le",
        target,
    )
    return target


def _store(tmp_path: Path) -> ArtifactStore:
    return ArtifactStore(AppPaths.for_home(tmp_path / "home").ensure())


def _commit_source(
    store: ArtifactStore,
    canonical: Path,
    *,
    cover: Path | None = None,
    title: str = TITLE,
    gain_db: float = 0.0,
) -> str:
    staging = store.stage("source-job")
    target = staging / "canonical.wav"
    shutil.copyfile(canonical, target)
    files = [_entry(target, "canonical")]
    if cover is not None:
        cover_target = staging / "cover.png"
        shutil.copyfile(cover, cover_target)
        files.append(_entry(cover_target, "cover"))
    metadata = {
        **TAGS,
        "title": title,
        "duration_s": DURATION_S,
        "sample_rate": 44_100,
        "channels": 2,
    }
    store.commit_source(
        staging,
        SOURCE_ID,
        {
            "schema_version": 1,
            "kind": "source",
            "source_id": SOURCE_ID,
            "created_at": "2026-11-16T09:00:00+00:00",
            "gain_db": gain_db,
            "metadata": metadata,
            "files": files,
        },
    )
    return SOURCE_ID


def _commit_separation(
    store: ArtifactStore,
    canonical: Path,
    *,
    gain_db: float = -2.0,
    roles: Sequence[str] = ALL_STEMS,
) -> None:
    staging = store.stage("separation-job")
    files = []
    for role in roles:
        target = staging / f"{role}.wav"
        shutil.copyfile(canonical, target)
        files.append(_entry(target, role))
    store.commit_separation(
        staging,
        SOURCE_ID,
        {
            "schema_version": 1,
            "kind": "separation",
            "source_id": SOURCE_ID,
            "created_at": "2026-11-16T09:05:00+00:00",
            "gain_db": gain_db,
            "files": files,
        },
    )


def _commit_render(
    store: ArtifactStore,
    canonical: Path,
    key: str,
    *,
    scope: str,
    semitones: int,
    roles: Sequence[str],
    gain_db: float,
    created_at: str,
) -> str:
    staging = store.stage(f"render-job-{key}")
    files = []
    for role in roles:
        target = staging / f"{role}.wav"
        shutil.copyfile(canonical, target)
        files.append(_entry(target, role))
    store.commit_render(
        staging,
        key,
        {
            "schema_version": 1,
            "kind": "render",
            "source_id": SOURCE_ID,
            "render_key": key,
            "created_at": created_at,
            "scope": scope,
            "semitones": semitones,
            "gain_db": gain_db,
            "files": files,
        },
    )
    return key


def _job_context(
    events: list[tuple[float, str | None, str | None]] | None = None,
    *,
    job_id: str = "job-export",
) -> JobContext:
    def update(fraction: float, stage: str | None, detail: str | None) -> None:
        if events is not None:
            events.append((fraction, stage, detail))

    return JobContext(
        job_id=job_id,
        kind=JobKind.EXPORT,
        cancel=CancelToken(),
        log=LOG,
        update=update,
    )


def _export(
    store: ArtifactStore,
    media: FfmpegTool,
    target: object,
    fmt: ExportFormat,
    destination: Path,
    *,
    job_id: str = "job-export",
    events: list[tuple[float, str | None, str | None]] | None = None,
    destination_name: str | None = None,
):
    return run_export_job(
        _job_context(events, job_id=job_id),
        artifacts=store,
        media=media,
        source_id=SOURCE_ID,
        target=target,  # type: ignore[arg-type]
        fmt=fmt,
        destination_dir=destination,
        destination_name=destination_name,
    )


