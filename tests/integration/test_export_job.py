    assert [first.path.name, second.path.name, third.path.name] == [
        f"{TITLE}.wav",
        f"{TITLE} (2).wav",
        f"{TITLE} (3).wav",
    ]
    assert hashlib.sha256(first.path.read_bytes()).hexdigest() == first_hash


