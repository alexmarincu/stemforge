class BlockingMedia:
    """A fake adapter that blocks inside decode until the token is cancelled."""

    def __init__(self) -> None:
        self.started = threading.Event()

    def probe(self, path: Path) -> MediaInfo:
        return MediaInfo(
            codec="pcm_s16le",
            sample_rate=44_100,
            channels=2,
            duration_s=1_800.0,
            format="wav",
            tags={},
        )

    def decode_canonical(
        self, src: Path, dst: Path, *, cancel: CancelToken, log: logging.Logger
    ) -> DecodeResult:
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(b"unfinished canonical")
        self.started.set()
        deadline = time.monotonic() + 10
        while not cancel.cancelled:
            if time.monotonic() > deadline:
                raise AssertionError("the test never cancelled the Job")
            time.sleep(0.005)
        cancel.check()
        raise AssertionError("unreachable")

    def extract_metadata(self, src: Path) -> CanonicalMetadata:
        raise AssertionError("metadata must not run after cancellation")

    def extract_cover(self, src: Path, dst_dir: Path) -> Path | None:
        raise AssertionError("cover extraction must not run after cancellation")

    def encode_preview(self, *args: object, **kwargs: object) -> None:
        raise AssertionError("preview must not run after cancellation")

    def encode_export(self, *args: object, **kwargs: object) -> None:
        raise AssertionError("export must not run during import")

    def sum_wavs(self, *args: object, **kwargs: object) -> None:
        raise AssertionError("summing must not run during import")

    def peak_dbfs(self, *args: object, **kwargs: object) -> float:
        raise AssertionError("peak measurement must not run after cancellation")


def test_cancelling_mid_decode_leaves_no_visible_artifact(
    tmp_path: Path, three_second_wav: Path
) -> None:
    media = BlockingMedia()
    with Harness(tmp_path / "home", media=media) as harness:
        source_id = hashlib.blake2b(three_second_wav.read_bytes(), digest_size=32).hexdigest()

        job_id = harness.service.import_local(three_second_wav)
        assert media.started.wait(10)
        assert harness.runner.cancel(job_id) is True
        assert harness.runner.wait_idle(timeout=10) is True

        snapshot = harness.runner.snapshot(job_id)
        assert snapshot.state is JobState.CANCELLED
        assert snapshot.error_code is None
        assert not (harness.paths.cache / "sources" / source_id).exists()
        assert not (harness.paths.cache / "staging" / job_id).exists()
        assert harness.service.snapshot().tracks == ()
        assert harness.service.recent_files() == ()

        report = harness.store.sweep_stale()
        assert report.removed_staging == ()
        assert list((harness.paths.cache / "staging").iterdir()) == []


