def test_permission_failures_are_coded(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, three_second_wav: Path
) -> None:
    """The copy path maps a write failure to ``storage.permission_denied``."""

    def denied(*args: object, **kwargs: object) -> None:
        raise OSError(errno.EACCES, "permission denied")

    monkeypatch.setattr("stemforge.pipeline.import_job.shutil.copyfile", denied)

    with Harness(tmp_path / "home", media=FfmpegTool()) as harness:
        job_id = harness.service.import_local(three_second_wav)
        assert harness.runner.wait_idle(timeout=30) is True
        snapshot = harness.runner.snapshot(job_id)

    assert snapshot.state is JobState.FAILED
    assert snapshot.error_code == errors.STORAGE_PERMISSION_DENIED
