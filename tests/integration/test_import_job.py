def test_local_import_commits_a_source_track_and_recent_file(
    tmp_path: Path, three_second_wav: Path, real_harness: Harness
) -> None:
    harness = real_harness
    home = harness.paths.data.parent
    fixture_bytes = three_second_wav.read_bytes()
    before = {path for path in tmp_path.rglob("*")}

    job_id = harness.service.import_local(three_second_wav)
    assert harness.runner.wait_idle(timeout=120) is True
    snapshot = harness.runner.snapshot(job_id)

    assert snapshot.state is JobState.SUCCEEDED, snapshot
    assert snapshot.progress == 1.0
    assert snapshot.stage == "Saving"
    assert snapshot.error_code is None
    assert snapshot.log_path is not None
    assert snapshot.log_path.is_file()

    source_id = snapshot.result_keys["source_id"]
    track_id = snapshot.result_keys["track_id"]
    expected_id = hashlib.blake2b(fixture_bytes, digest_size=32).hexdigest()
    assert source_id == expected_id

    source_dir = harness.paths.cache / "sources" / source_id
    assert source_dir.is_dir()
    manifest_path = source_dir / "source.json"
    assert manifest_path.is_file()
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert manifest["kind"] == "source"
    assert manifest["source_id"] == source_id
    assert manifest["content_hash"] == source_id
    assert manifest["origin"] == str(three_second_wav)
    assert manifest["metadata"]["title"] == "three-seconds"
    assert manifest["downmixed"] is False
    roles = {entry["role"]: entry["path"] for entry in manifest["files"]}
    assert {"native", "canonical", "preview"} <= set(roles)
    for relative in roles.values():
        assert (source_dir / relative).is_file()

    tool = FfmpegTool()
    canonical = tool.probe(source_dir / roles["canonical"])
    assert canonical.codec == "pcm_f32le"
    assert canonical.sample_rate == 44_100
    assert canonical.channels == 2
    assert canonical.duration_s == pytest.approx(3.0, abs=0.05)
    preview = tool.probe(source_dir / roles["preview"])
    assert preview.codec == "mp3"
    assert preview.duration_s == pytest.approx(3.0, abs=0.05)

    workspace = harness.service.snapshot()
    assert len(workspace) == 1
    track = workspace.tracks[0]
    assert track.track_id == track_id
    assert track.source.source_id == source_id
    assert track.source.canonical_path is not None
    assert track.source.canonical_path.is_file()
    assert track.title == "three-seconds"
    assert track.source.downmixed is False

    recent = harness.service.recent_files()
    assert len(recent) == 1
    assert recent[0].source_id == source_id
    assert recent[0].title == "three-seconds"
    assert Path(recent[0].origin) == three_second_wav
    assert recent[0].duration_s == pytest.approx(3.0, abs=0.05)

    restarted = SettingsStore(harness.paths)
    assert [entry.source_id for entry in restarted.recent_files()] == [source_id]
    assert harness.store.find_source(source_id) is not None

    created = {path for path in tmp_path.rglob("*")} - before
    assert created
    assert all(path.is_relative_to(home) for path in created), sorted(
        str(path) for path in created if not path.is_relative_to(home)
    )


