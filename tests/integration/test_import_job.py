def _run_cli(home: Path, *arguments: str, cwd: Path) -> subprocess.CompletedProcess[str]:
    environment = os.environ.copy()
    environment["STEMFORGE_HOME"] = str(home)
    environment["PYTHONDONTWRITEBYTECODE"] = "1"
    environment.pop("STEMFORGE_LOG_LEVEL", None)
    return subprocess.run(
        [sys.executable, "-m", "stemforge", *arguments],
        cwd=cwd,
        env=environment,
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
    )


def test_the_headless_import_cli_exits_zero_and_prints_one_line(
    tmp_path: Path, three_second_wav: Path
) -> None:
    home = tmp_path / "home"
    work = tmp_path / "work"
    work.mkdir()
    before = {path for path in tmp_path.rglob("*")}

    result = _run_cli(home, "--import", str(three_second_wav), cwd=work)

    assert result.returncode == 0, result.stderr
    lines = result.stdout.splitlines()
    assert len(lines) == 1
    assert lines[0].startswith('imported "three-seconds" source=')
    assert " track=" in lines[0]
    assert not (work / ".nicegui").exists()
    assert (home / "config" / "settings.json").is_file()
    created = {path for path in tmp_path.rglob("*")} - before
    assert all(path.is_relative_to(home) for path in created)


