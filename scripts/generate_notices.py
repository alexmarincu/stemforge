def _buildinfo_text(
    component: NativeComponent,
    vendor: Mapping[str, object],
    config: ReleaseConfig,
) -> str:
    components = vendor.get("components", {})
    selected = []
    if isinstance(components, dict):
        for name in component.vendor:
            entry = components.get(name)
            if isinstance(entry, dict):
                selected.append({name: entry})
    payload = {
        "component": component.id,
        "licence": component.spdx,
        "source": component.source,
        "vendor_lock": config.paths["vendor_lock"],
        "vendor_records": selected,
        "note": (
            "The shipped runtime `-buildconf`/`--version` output is captured by the "
            "release build into this directory; the values above are the committed "
            "provenance record from packaging/vendor.lock.json."
        ),
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


