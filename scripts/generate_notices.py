class ReleaseConfigError(ValueError):
    """``packaging/release.toml`` still carries a placeholder or is malformed."""


@dataclass(frozen=True, slots=True)
class ReleaseConfig:
    """The release identity and every generated URL's only source."""

    path: Path
    schema: int
    project_name: str
    license: str
    copyright: str
    version_file: str
    repo_url: str
    releases_url: str
    source_offer_contact: str
    offer_years: int
    start_year: int
    source_archive: str
    third_party_sources_archive: str
    paths: Mapping[str, str]

    @property
    def end_year(self) -> int:
        """The last year the written offer is valid."""
        return self.start_year + self.offer_years

    def require_valid(self) -> None:
        problems = release_problems(self)
        if problems:
            raise ReleaseConfigError("; ".join(problems))

    def asset_url(self, version: str, asset: str) -> str:
        return f"{self.releases_url}/download/v{version}/{asset}"

    def tag_url(self, version: str) -> str:
        return f"{self.releases_url}/tag/v{version}"


@dataclass(frozen=True, slots=True)
class LicenceFile:
    """One upstream licence file to pool by content."""

    name: str
    data: bytes


@dataclass(frozen=True, slots=True)
class PackageRecord:
    """One uv.lock package with the metadata the notices need."""

    name: str
    version: str
    spdx: str
    source: str
    group: Group
    platform: str
    files: tuple[LicenceFile, ...] = ()
    common_texts: tuple[str, ...] = ()
    note: str | None = None


@dataclass(frozen=True, slots=True)
class NativeComponent:
    """One curated non-Python component from ``native.toml``."""

    id: str
    title: str
    kind: str
    spdx: str
    homepage: str
    source: str
    notice: str
    copyright: str = ""
    texts: tuple[str, ...] = ()
    packages: tuple[str, ...] = ()
    vendor: tuple[str, ...] = ()
    assets: tuple[Mapping[str, object], ...] = ()
    buildinfo: bool = False
    version: str = ""


@dataclass(frozen=True, slots=True)
class GeneratedTree:
    """The generated root and every file it wrote."""

    root: Path
    files: tuple[Path, ...]


@dataclass(frozen=True, slots=True)
class CheckResult:
    """The outcome of comparing a committed tree against a fresh generation."""

    ok: bool
    checked_files: int
    first_difference: str | None
    summary: str
    detail: str


def load_release(
    path: Path = Path("packaging/release.toml"),
    *,
    overrides: Mapping[str, object] | None = None,
) -> ReleaseConfig:
    """Read ``release.toml``; ``overrides`` exists for the placeholder tests."""
    with path.open("rb") as handle:
        data = tomllib.load(handle)
    project = _mapping(data.get("project"), "project")
    repo = _mapping(data.get("repo"), "repo")
    offer = _mapping(data.get("source_offer"), "source_offer")
    assets = _mapping(data.get("assets"), "assets")
    paths = {str(key): str(value) for key, value in _mapping(data.get("paths"), "paths").items()}
    config = ReleaseConfig(
        path=path,
        schema=int(data.get("schema", 0)),
        project_name=str(project.get("name", "")),
        license=str(project.get("license", "")),
        copyright=str(project.get("copyright", "")),
        version_file=str(project.get("version_file", "")),
        repo_url=str(repo.get("url", "")),
        releases_url=str(repo.get("releases_url", "")),
        source_offer_contact=str(repo.get("source_offer_contact", "")),
        offer_years=int(offer.get("years", 0)),
        start_year=int(offer.get("start_year", 0)),
        source_archive=str(assets.get("source_archive", "")),
        third_party_sources_archive=str(assets.get("third_party_sources_archive", "")),
        paths=paths,
    )
    if overrides:
        config = ReleaseConfig(
            **{
                **{field: getattr(config, field) for field in ReleaseConfig.__dataclass_fields__},
                **{str(key): value for key, value in overrides.items()},
            }
        )
    return config


def release_problems(config: ReleaseConfig) -> tuple[str, ...]:
    """Return every placeholder or malformed value in ``release.toml``."""
    problems: list[str] = []
    if config.schema != 1:
        problems.append(f"schema must be 1, got {config.schema!r}")
    if config.license != PROJECT_LICENCE_TEXT:
        problems.append(f"project license must be {PROJECT_LICENCE_TEXT}")
    for label, value in (
        ("project.name", config.project_name),
        ("project.copyright", config.copyright),
        ("project.version_file", config.version_file),
    ):
        if not value.strip():
            problems.append(f"{label} must not be empty")
    for label, value in (
        ("repo.url", config.repo_url),
        ("repo.releases_url", config.releases_url),
        ("repo.source_offer_contact", config.source_offer_contact),
    ):
        problems.extend(_url_problems(label, value))
    if config.offer_years != 3:
        problems.append("source_offer.years must be 3 (GPL-3.0 section 6(b))")
    if config.start_year < 2020:
        problems.append("source_offer.start_year looks unset")
    for label, value in (
        ("assets.source_archive", config.source_archive),
        ("assets.third_party_sources_archive", config.third_party_sources_archive),
    ):
        if "{version}" not in value:
            problems.append(f"{label} must contain {{version}}")
        problems.extend(_placeholder_problems(label, value))
    for key in (
        "license",
        "notices",
        "source_offer",
        "licenses_dir",
        "uv_lock",
        "venv",
        "vendor_lock",
        "vendor_sources",
        "native_manifest",
        "python_manifest",
        "license_texts",
    ):
        if not config.paths.get(key, "").strip():
            problems.append(f"paths.{key} must not be empty")
    return tuple(problems)


def _url_problems(label: str, value: str) -> list[str]:
    problems = _placeholder_problems(label, value)
    if value and not value.startswith("https://"):
        problems.append(f"{label} must use https")
    return problems


def _placeholder_problems(label: str, value: str) -> list[str]:
    text = value.strip()
    if not text:
        return [f"{label} must not be empty"]
    lowered = text.lower()
    problems = [
        f"{label} contains the placeholder {token!r}"
        for token in PLACEHOLDER_TOKENS
        if token in lowered
    ]
    if "<" in text or ">" in text:
        problems.append(f"{label} still looks like a <PLACEHOLDER>")
    return problems


def read_version(version_file: Path) -> str:
    """Read ``__version__`` without importing the package."""
    tree = ast.parse(version_file.read_text(encoding="utf-8"), filename=str(version_file))
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "__version__":
                    value = ast.literal_eval(node.value)
                    if isinstance(value, str) and value:
                        return value
    raise ValueError(f"{version_file} does not define __version__")


def generate(
    root: Path,
    destination: Path,
    *,
    site_packages: Path | None = None,
) -> GeneratedTree:
    """Render the complete licence tree into ``destination``."""
    root = root.resolve()
    config = load_release(root / "packaging/release.toml")
    config.require_valid()
    version = read_version(root / config.version_file)
    lock = _read_lock(root / config.paths["uv_lock"])
    vendor = _read_json(root / config.paths["vendor_lock"])
    _verify_vendor_sources(root / config.paths["vendor_sources"], vendor)
    _verify_source_offer_record(vendor, config)
    native = _read_native(root / config.paths["native_manifest"])
    overrides = _read_python_overrides(root / config.paths["python_manifest"])
    dist_infos = _dist_info_map(site_packages or _site_packages(root / config.paths["venv"]))

    records = _package_records(lock, dist_infos, overrides, config, version)
    components = _native_records(native, vendor, lock)

    writer = _Writer(destination)
    texts_dir = root / config.paths["license_texts"]
    common_keys = {PROJECT_LICENCE_TEXT}
    for record in records:
        common_keys.update(record.common_texts)
    for component in components:
        common_keys.update(component.texts)
        for asset in component.assets:
            common_keys.update(str(item) for item in asset.get("texts", ()))
    _write_common_texts(writer, texts_dir, common_keys)
    pool = _write_package_texts(writer, records)

    _write_root_license(writer, texts_dir, config)
    _write_native(writer, components, vendor, config)
    _write_frontend(writer, components)
    _write_readme(writer, config, version, components, records)
    _write_dependencies(writer, config, records, pool)
    _write_notices(writer, config, version, components, records)
    _write_source_offer(writer, config, version, records, vendor)

    writer.assert_safe()
    writer.prune()
    return GeneratedTree(root=writer.root, files=tuple(writer.written))


def check(
    root: Path,
    *,
    committed_root: Path | None = None,
    scratch: Path | None = None,
    site_packages: Path | None = None,
) -> CheckResult:
    """Regenerate into a temporary directory and compare with the committed tree."""
    scratch_root = Path(scratch) if scratch is not None else None
    if scratch_root is not None:
        scratch_root.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="stemforge-notices-", dir=scratch_root) as raw:
        generated = generate(root, Path(raw) / "out", site_packages=site_packages)
        return compare_trees(
            committed=Path(committed_root) if committed_root is not None else Path(root),
            generated=generated.root,
        )


def compare_trees(*, committed: Path, generated: Path) -> CheckResult:
    """Byte-compare the managed files in ``committed`` and ``generated``."""
    expected = _managed_files(generated)
    actual = _managed_files(committed)
    paths = sorted(set(expected) | set(actual))
    changed: list[str] = []
    missing: list[str] = []
    extra: list[str] = []
    for relative in paths:
        if relative not in actual:
            missing.append(relative)
        elif relative not in expected:
            extra.append(relative)
        elif actual[relative].read_bytes() != expected[relative].read_bytes():
            changed.append(relative)
    differences = sorted(changed + missing + extra)
    if not differences:
        return CheckResult(
            ok=True,
            checked_files=len(paths),
            first_difference=None,
            summary=f"{len(paths)} files match",
            detail="",
        )
    first = differences[0]
    summary = (
        f"{len(differences)} difference(s): {len(changed)} changed, "
        f"{len(missing)} missing, {len(extra)} extra; first: {first}"
    )
    return CheckResult(
        ok=False,
        checked_files=len(paths),
        first_difference=first,
        summary=summary,
        detail=_difference_detail(first, committed, generated),
    )


def _difference_detail(relative: str, committed: Path, generated: Path) -> str:
    left = committed / relative
    right = generated / relative
    if left.is_file() and right.is_file():
        try:
            old = left.read_text(encoding="utf-8").splitlines(keepends=True)
            new = right.read_text(encoding="utf-8").splitlines(keepends=True)
        except UnicodeDecodeError:
            return f"{relative}: binary content differs ({left.stat().st_size} vs "
            f"{right.stat().st_size} bytes)"
        diff = list(
            difflib.unified_diff(
                old,
                new,
                fromfile=f"committed/{relative}",
                tofile=f"generated/{relative}",
                n=2,
            )
        )
        return "".join(diff[:60])
    if not left.is_file():
        return f"{relative}: missing from the committed tree"
    return f"{relative}: extra file in the committed tree"


def _managed_files(root: Path) -> dict[str, Path]:
    managed: dict[str, Path] = {}
    for name in ("LICENSE", "THIRD_PARTY_NOTICES.md", "SOURCE_OFFER.md"):
        path = root / name
        if path.is_file():
            managed[name] = path
    licenses = root / "LICENSES"
    if licenses.is_dir():
        for path in sorted(licenses.rglob("*")):
            if path.is_file():
                managed[path.relative_to(root).as_posix()] = path
    return managed


class _Writer:
    """Write text files under one root, tracking them and refusing binaries."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.written: list[Path] = []
        self._root = root.resolve()
        root.mkdir(parents=True, exist_ok=True)

    def write(self, relative: str, text: str) -> None:
        self.write_bytes(relative, text.encode("utf-8"))

    def write_bytes(self, relative: str, data: bytes) -> None:
        path = self.root / relative
        resolved = path.resolve()
        if self._root not in resolved.parents and resolved != self._root:
            raise ValueError(f"refusing to write outside the output root: {relative}")
        path.parent.mkdir(parents=True, exist_ok=True)
        # Git stores LF; upstream licence files occasionally arrive with CRLF.
        # Normalising here keeps the committed tree byte-identical to a fresh
        # generation on every platform (and avoids an autocrlf drift trap).
        path.write_bytes(data.replace(b"\r\n", b"\n").replace(b"\r", b"\n"))
        self.written.append(path)

    def assert_safe(self) -> None:
        for path in self.written:
            name = path.name.lower()
            if name.endswith(FORBIDDEN_SUFFIXES):
                raise ValueError(f"refusing to ship a binary or weight: {path}")
            if "torchaudio" in path.as_posix():
                raise ValueError(f"torchaudio must not appear in the licence tree: {path}")
            if "torchaudio" in path.read_bytes().decode("utf-8", errors="ignore"):
                raise ValueError(f"torchaudio must not appear in generated text: {path}")

    def prune(self) -> None:
        """Remove stale files under ``LICENSES/`` that this run did not write."""
        licenses = self.root / "LICENSES"
        if not licenses.is_dir():
            return
        written = {path.resolve() for path in self.written}
        for path in sorted(licenses.rglob("*"), key=lambda item: len(item.parts), reverse=True):
            if path.is_file() and path.resolve() not in written:
                path.unlink()
            elif path.is_dir() and not any(path.iterdir()):
                path.rmdir()


def _read_lock(path: Path) -> Mapping[str, object]:
    with path.open("rb") as handle:
        data = tomllib.load(handle)
    if not isinstance(data.get("package"), list):
        raise ValueError(f"{path} has no package table")
    return data


def _read_json(path: Path) -> Mapping[str, object]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return data


def _verify_vendor_sources(path: Path, vendor: Mapping[str, object]) -> None:
    """Read the human-readable vendor record and cross-check it with the lock.

    ``SOURCES.md`` is the prose source-offer input from ticket 19. It is not a
    second machine-readable pin list; the lock wins, but every pinned component
    must appear in the record, and the record must keep the offer term and the
    no-weights statement.
    """
    if not path.is_file():
        raise FileNotFoundError(f"missing the vendor source record: {path}")
    text = path.read_text(encoding="utf-8")
    components = vendor.get("components", {})
    if isinstance(components, dict):
        missing = [name for name in components if f"`{name}`" not in text]
        if missing:
            raise ValueError(
                f"{path} does not mention the pinned vendor component(s): {', '.join(missing)}"
            )
    for phrase in ("three years", "No weights"):
        if phrase not in text:
            raise ValueError(f"{path} lost its {phrase!r} statement")


def _verify_source_offer_record(vendor: Mapping[str, object], config: ReleaseConfig) -> None:
    """Refuse a vendor lock whose duplicate URLs disagree with ``release.toml``.

    ``packaging/release.toml`` is the only source of truth; the vendor lock's
    ``source_offer`` block is the ticket-19 record. Divergence is a config bug,
    not something to silently prefer.
    """
    offer = vendor.get("source_offer")
    if not isinstance(offer, dict):
        raise ValueError("vendor.lock.json has no source_offer block")
    checks = (
        ("contact", config.source_offer_contact),
        ("release_page", config.releases_url),
        ("offer_years", config.offer_years),
    )
    for field, expected in checks:
        actual = offer.get(field)
        if actual != expected:
            raise ValueError(
                f"vendor.lock.json source_offer.{field} is {actual!r}, "
                f"but packaging/release.toml says {expected!r}"
            )


def _read_native(path: Path) -> tuple[NativeComponent, ...]:
    with path.open("rb") as handle:
        data = tomllib.load(handle)
    entries = data.get("component")
    if not isinstance(entries, list):
        raise ValueError(f"{path} has no [[component]] entries")
    components: list[NativeComponent] = []
    for entry in entries:
        mapping = _mapping(entry, "component")
        assets = mapping.get("assets", [])
        if not isinstance(assets, list):
            raise ValueError(f"{path}: assets must be a list")
        components.append(
            NativeComponent(
                id=str(mapping["id"]),
                title=str(mapping["title"]),
                kind=str(mapping["kind"]),
                spdx=str(mapping["spdx"]),
                homepage=str(mapping.get("homepage", "")),
                source=str(mapping.get("source", "")),
                notice=str(mapping.get("notice", "")).strip(),
                copyright=str(mapping.get("copyright", "")),
                texts=tuple(str(item) for item in mapping.get("texts", ())),
                packages=tuple(str(item) for item in mapping.get("packages", ())),
                vendor=tuple(str(item) for item in mapping.get("vendor", ())),
                assets=tuple(_mapping(item, "asset") for item in assets),
                buildinfo=bool(mapping.get("buildinfo", False)),
            )
        )
    return tuple(components)


def _read_python_overrides(path: Path) -> Mapping[str, Mapping[str, object]]:
    with path.open("rb") as handle:
        data = tomllib.load(handle)
    entries = data.get("override", [])
    if not isinstance(entries, list):
        raise ValueError(f"{path} has no [[override]] entries")
    return {
        str(_mapping(entry, "override")["name"]): _mapping(entry, "override") for entry in entries
    }


def _mapping(value: object, label: str) -> Mapping[str, object]:
    if not isinstance(value, dict):
        raise ValueError(f"{label} must be a table")
    return value


def _site_packages(venv: Path) -> Path:
    candidates = sorted(venv.glob("lib/python*/site-packages"))
    if candidates:
        return candidates[-1]
    win = venv / "Lib/site-packages"
    if win.is_dir():
        return win
    raise FileNotFoundError(
        f"no site-packages under {venv}; run `uv sync --frozen` before generating notices"
    )


def _normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _dist_info_map(site_packages: Path) -> Mapping[str, Path]:
    found: dict[str, Path] = {}
    for path in sorted(site_packages.glob("*.dist-info")):
        name = path.name.split("-")[0]
        found[_normalize(name)] = path
    return found


def _package_records(
    lock: Mapping[str, object],
    dist_infos: Mapping[str, Path],
    overrides: Mapping[str, Mapping[str, object]],
    config: ReleaseConfig,
    project_version: str,
) -> tuple[PackageRecord, ...]:
    packages = lock["package"]
    if not isinstance(packages, list):
        raise ValueError("uv.lock package must be a list")
    by_name: dict[str, Mapping[str, object]] = {}
    for entry in packages:
        mapping = _mapping(entry, "package")
        by_name[str(mapping["name"])] = mapping
    root = next((item for item in by_name.values() if item["name"] == "stemforge"), None)
    runtime_dependencies = root.get("dependencies", []) if root is not None else []
    runtime_names: tuple[str, ...] = ()
    if isinstance(runtime_dependencies, list):
        runtime_names = tuple(
            str(item["name"])
            for item in runtime_dependencies
            if isinstance(item, dict) and "name" in item
        )
    runtime = _closure(by_name, runtime_names)
    build = _closure(by_name, _group_names(root, "build"))
    development = _closure(by_name, _group_names(root, "dev"))
    records: list[PackageRecord] = []
    for name in sorted(by_name):
        mapping = by_name[name]
        if name == "stemforge":
            records.append(
                PackageRecord(
                    name=name,
                    version=project_version,
                    spdx=config.license,
                    source=config.repo_url,
                    group="runtime",
                    platform="all",
                    common_texts=(config.license,),
                )
            )
            continue
        version = str(mapping["version"])
        override = overrides.get(name, {})
        # A package can be a build-group dependency and still be shipped: the
        # Linux bundle uses the build group to compile PyGObject for the frozen
        # CPython. The override says how the licence table must describe it.
        override_group = override.get("group")
        if override_group is not None:
            if override_group == "runtime":
                group: Group = "runtime"
            elif override_group == "development":
                group = "development"
            elif override_group == "build":
                group = "build"
            else:
                raise ValueError(
                    f"{name}: override group {override_group!r} is not "
                    "runtime, development, or build"
                )
        elif name in runtime:
            group = "runtime"
        elif name in build:
            group = "build"
        elif name in development:
            group = "development"
        else:
            group = "runtime"
        dist_info = dist_infos.get(_normalize(name))
        spdx = _resolve_spdx(name, dist_info, override)
        source = str(override.get("source") or _source_from_dist_info(dist_info, name, version))
        common_texts = tuple(str(item) for item in override.get("texts", ()))
        files: tuple[LicenceFile, ...] = ()
        if dist_info is not None and not common_texts:
            files = _licence_files(dist_info)
        if not common_texts and not files:
            raise ValueError(
                f"no licence entry for uv.lock package {name} {version}: add it to "
                f"packaging/licenses/python.toml"
            )
        records.append(
            PackageRecord(
                name=name,
                version=version,
                spdx=spdx,
                source=source,
                group=group,
                platform=str(override.get("platform", "all")),
                files=files,
                common_texts=common_texts,
                note=str(override["note"]) if "note" in override else None,
            )
        )
    return tuple(records)


def _group_names(root: Mapping[str, object] | None, group: str) -> tuple[str, ...]:
    if root is None:
        return ()
    groups = root.get("dev-dependencies")
    if not isinstance(groups, dict):
        return ()
    entries = groups.get(group, [])
    if not isinstance(entries, list):
        return ()
    names: list[str] = []
    for entry in entries:
        if isinstance(entry, str):
            names.append(entry)
        elif isinstance(entry, dict) and "name" in entry:
            names.append(str(entry["name"]))
    return tuple(names)


def _closure(by_name: Mapping[str, Mapping[str, object]], roots: Iterable[str]) -> set[str]:
    seen: set[str] = set()
    stack = list(roots)
    while stack:
        name = stack.pop()
        if name in seen or name not in by_name:
            continue
        seen.add(name)
        dependencies = by_name[name].get("dependencies", [])
        if isinstance(dependencies, list):
            for dependency in dependencies:
                if isinstance(dependency, dict) and "name" in dependency:
                    stack.append(str(dependency["name"]))
    return seen


def _resolve_spdx(
    name: str,
    dist_info: Path | None,
    override: Mapping[str, object],
) -> str:
    if "spdx" in override:
        return str(override["spdx"])
    if dist_info is not None:
        expression = _spdx_from_metadata(_metadata(dist_info))
        if expression:
            return expression
    raise ValueError(
        f"cannot determine the licence of uv.lock package {name}: add an [[override]] "
        f"to packaging/licenses/python.toml"
    )


def _metadata(dist_info: Path) -> email.message.Message:
    return email.message_from_bytes((dist_info / "METADATA").read_bytes())


def _spdx_from_metadata(message: email.message.Message) -> str | None:
    expression = (message.get("License-Expression") or "").strip()
    if expression:
        return _collapse(expression)
    declared = (message.get("License") or "").strip()
    if declared:
        collapsed = _collapse(declared)
        alias = _LICENCE_ALIASES.get(collapsed.upper())
        if alias:
            return alias
        if _SPDX_EXPRESSION.match(collapsed):
            return collapsed
    for classifier in message.get_all("Classifier") or []:
        mapped = _CLASSIFIER_SPDX.get(classifier)
        if mapped:
            return mapped
    return None


def _collapse(value: str) -> str:
    return " ".join(value.split())


def _source_from_dist_info(dist_info: Path | None, name: str, version: str) -> str:
    if dist_info is not None:
        message = _metadata(dist_info)
        labels: dict[str, str] = {}
        for entry in message.get_all("Project-URL") or []:
            label, separator, url = entry.partition(",")
            if separator and url.strip().startswith("https://"):
                labels[label.strip().lower()] = url.strip()
        for key in ("source", "sources", "repository", "code", "github", "homepage"):
            if key in labels:
                return labels[key]
        home = (message.get("Home-page") or "").strip()
        if home.startswith("https://"):
            return home
    return f"https://pypi.org/project/{name}/{version}/"


def _licence_files(dist_info: Path) -> tuple[LicenceFile, ...]:
    files: list[LicenceFile] = []
    seen: set[str] = set()
    licenses = dist_info / "licenses"
    if licenses.is_dir():
        for path in sorted(licenses.rglob("*")):
            if path.is_file():
                name = path.relative_to(licenses).as_posix()
                files.append(LicenceFile(name=name, data=path.read_bytes()))
                seen.add(name)
    for entry in _metadata(dist_info).get_all("License-File") or []:
        relative = entry.strip().replace("\\", "/")
        if relative in seen:
            continue
        for candidate in (dist_info / relative, dist_info.parent / relative):
            if candidate.is_file():
                files.append(LicenceFile(name=relative, data=candidate.read_bytes()))
                seen.add(relative)
                break
    for path in sorted(dist_info.iterdir()):
        if not path.is_file() or path.name in seen:
            continue
        if path.name.upper().startswith(("LICENSE", "COPYING", "NOTICE")):
            files.append(LicenceFile(name=path.name, data=path.read_bytes()))
            seen.add(path.name)
    return tuple(files)


def _native_records(
    components: Sequence[NativeComponent],
    vendor: Mapping[str, object],
    lock: Mapping[str, object],
) -> tuple[NativeComponent, ...]:
    vendor_components = vendor.get("components", {})
    if not isinstance(vendor_components, dict):
        vendor_components = {}
    package_versions = {
        str(entry["name"]): str(entry["version"])
        for entry in lock["package"]
        if isinstance(entry, dict) and "name" in entry and "version" in entry
    }
    resolved: list[NativeComponent] = []
    for component in components:
        versions: list[str] = []
        for vendor_name in component.vendor:
            entry = vendor_components.get(vendor_name)
            if isinstance(entry, dict) and "version" in entry:
                versions.append(str(entry["version"]))
        if not versions:
            versions = [
                package_versions[name] for name in component.packages if name in package_versions
            ]
        version = ", ".join(dict.fromkeys(versions)) if versions else ""
        resolved.append(
            NativeComponent(
                id=component.id,
                title=component.title,
                kind=component.kind,
                spdx=component.spdx,
                homepage=component.homepage,
                source=component.source,
                notice=component.notice,
                copyright=component.copyright,
                texts=component.texts,
                packages=component.packages,
                vendor=component.vendor,
                assets=component.assets,
                buildinfo=component.buildinfo,
                version=version,
            )
        )
    return tuple(resolved)


