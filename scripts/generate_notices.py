def _write_package_texts(
    writer: _Writer, records: Sequence[PackageRecord]
) -> Mapping[tuple[str, str], str]:
    """Write deduplicated upstream texts and return (package, name) -> pool path."""
    pool: dict[str, str] = {}
    used: dict[str, str] = {}
    mapping: dict[tuple[str, str], str] = {}
    for record in records:
        for licence in sorted(record.files, key=lambda item: (item.name, item.data)):
            payload = licence.data.replace(b"\r\n", b"\n").replace(b"\r", b"\n")
            digest = hashlib.sha256(payload).hexdigest()
            if digest not in pool:
                slug = _slug(Path(licence.name).name) or "license"
                candidate = f"{slug}-{digest[:12]}.txt"
                if used.get(candidate, digest) != digest:
                    candidate = f"{slug}-{digest}.txt"
                used[candidate] = digest
                pool[digest] = f"LICENSES/texts/{candidate}"
                writer.write_bytes(pool[digest], payload)
            mapping[(record.name, licence.name)] = pool[digest]
    return mapping


def _slug(value: str) -> str:
    return re.sub(r"[^a-z0-9.]+", "-", value.lower()).strip("-")


