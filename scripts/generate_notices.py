"""Generate the shipped licence tree from the lock, manifests, and dist-info.

Inputs (all read-only, no network):

* ``uv.lock`` — every resolved package and version; the package set is taken
  from here, never from the local environment, so a Windows checkout covers the
  same packages as Linux.
* the build virtualenv's ``*.dist-info`` — ``METADATA`` licence expression and
  project URLs, plus ``licenses/`` and ``License-File`` contents. Deduplicated
  into ``LICENSES/texts/`` by SHA-256.
* ``packaging/licenses/native.toml`` — curated non-Python components (FFmpeg,
  Rubber Band, libsndfile, Deno, PyTorch/NumPy runtime libraries, WebView2, and
  NiceGUI's Quasar/Vue/font assets).
* ``packaging/licenses/python.toml`` — curated overrides for wheels that are
  absent on one platform or carry no licence declaration.
* ``packaging/vendor.lock.json`` and ``packaging/vendor/SOURCES.md`` — the
  pinned archives and the GPL written-offer record.
* ``packaging/release.toml`` — the only source of repository and release URLs.

Outputs: ``LICENSE``, ``THIRD_PARTY_NOTICES.md``, ``SOURCE_OFFER.md``, and
``LICENSES/``. ``--check`` regenerates into a temporary directory and
byte-compares; it fails on drift, on a placeholder URL, or on a locked package
with no licence entry.

No model weights and no vendor binaries are ever written; only text.
"""

