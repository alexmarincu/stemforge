def main(argv: Sequence[str] | None = None) -> int:
    """CLI entry point: ``--check``, ``--check-release``, or write in place."""
    default_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=default_root)
    parser.add_argument("--output", type=Path, help="write to another directory")
    parser.add_argument("--check", action="store_true", help="fail on any drift")
    parser.add_argument(
        "--check-release",
        action="store_true",
        help="only validate packaging/release.toml placeholders",
    )
    args = parser.parse_args(argv)
    if args.check_release:
        config = load_release(args.root / "packaging/release.toml")
        problems = release_problems(config)
        if problems:
            for problem in problems:
                print(f"release.toml: {problem}", file=sys.stderr)
            return 1
        print("release.toml: ok")
        return 0
    try:
        if args.check:
            result = check(args.root, committed_root=args.root)
            print(result.summary)
            if not result.ok:
                if result.detail:
                    print(result.detail)
                return 1
            return 0
        destination = args.output if args.output is not None else args.root
        generated = generate(args.root, destination)
    except (ReleaseConfigError, FileNotFoundError, ValueError) as error:
        print(f"generate_notices: {error}", file=sys.stderr)
        return 1
    print(f"wrote {len(generated.files)} files under {generated.root}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
